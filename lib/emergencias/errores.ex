defmodule Emergencias.Errores do
  @moduledoc "Traduce los motivos de error de dominio a mensajes legibles."

  def mensaje(:ya_existe), do: "El identificador ya existe."
  def mensaje(:no_encontrado), do: "No se encontró el registro indicado."
  def mensaje(:zona_no_existe), do: "La zona no existe. Regístrela primero (menú: Zonas afectadas > Registrar zona; comando: register_zone). Solo coordinador o administrador pueden registrar zonas."
  def mensaje(:zona_invalida), do: "La zona es obligatoria."
  def mensaje(:campo_vacio), do: "Hay un campo obligatorio vacío."
  def mensaje(:no_es_numero), do: "Se esperaba un número entero."
  def mensaje(:cantidad_negativa), do: "Las cantidades no pueden ser negativas."
  def mensaje(:cantidad_invalida), do: "La cantidad debe ser mayor que cero."
  def mensaje(:cantidad_insuficiente), do: "La cantidad solicitada supera la disponible."
  def mensaje(:inventario_insuficiente), do: "Inventario insuficiente: no se puede asignar más de lo disponible."
  def mensaje(:excede_requerido), do: "La cantidad supera lo que aún necesita la solicitud."
  def mensaje(:necesidad_cerrada), do: "La necesidad ya está cerrada (atendida o cancelada) y no puede consumir recursos."
  def mensaje(:categoria_no_coincide), do: "La categoría del recurso no corresponde al tipo de la necesidad."
  def mensaje(:tipo_invalido), do: "Tipo de necesidad inválido (agua, alimentos, medicamentos, primeros_auxilios, refugio, transporte, rescate, otra)."
  def mensaje(:prioridad_invalida), do: "Prioridad inválida (critica, alta, media, baja)."
  def mensaje(:nivel_invalido), do: "Nivel inválido (critico, alto, medio, bajo)."
  def mensaje(:estado_invalido), do: "Estado inválido."
  def mensaje(:tamano_invalido), do: "Tamaño inválido (pequeno, mediano, grande)."
  def mensaje(:tipo_reporte_invalido), do: "Tipo de reporte inválido (lost/found)."
  def mensaje(:tipo_usuario_invalido), do: "Tipo de usuario inválido (ciudadano, voluntario, coordinador, administrador)."
  def mensaje(:credenciales_invalidas), do: "Credenciales inválidas."
  def mensaje(:no_conectado), do: "El usuario no está conectado."
  def mensaje(:jerarquia_invalida), do: "Jerarquía inválida: zona → sector → punto de atención."
  def mensaje(:padre_no_existe), do: "El sector padre no existe en esa zona."
  def mensaje(:persona_no_existe), do: "La persona no está registrada."
  def mensaje(:albergue_no_existe), do: "El albergue no existe."
  def mensaje(:sin_cupo), do: "El albergue no tiene cupos: se alcanzó la capacidad máxima."
  def mensaje(:ya_ingresado), do: "La persona ya está en ese albergue."
  def mensaje(:ya_alojada), do: "La persona ya está alojada en un albergue."
  def mensaje(:no_esta_en_albergue), do: "La persona no está en ese albergue."
  def mensaje(:ya_resuelto), do: "El reporte ya estaba resuelto; no se puede cerrar dos veces."
  def mensaje(:ya_entregado), do: "El mensaje ya estaba entregado."
  def mensaje(:tipos_incorrectos), do: "Debe indicar primero un reporte 'perdida' y luego uno 'encontrada'."
  def mensaje(:ubicacion_incorrecta), do: "El recurso no está en el centro de origen indicado."
  def mensaje(:mismo_centro), do: "El origen y el destino deben ser distintos."
  def mensaje({:transicion_invalida, de, a}), do: "Transición de estado inválida: #{de} → #{a}."
  def mensaje({:filtro_invalido, clave}), do: "Filtro no soportado: #{clave}."
  def mensaje({:uso, uso}), do: "Uso: #{uso}"
  def mensaje(:sin_permiso), do: "Su tipo de usuario no tiene permiso para este comando."
  def mensaje(otro), do: "Error: #{inspect(otro)}"
end
